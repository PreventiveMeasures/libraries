// The semver crate's order, which picks the version a name alone is for.
describe('vendoredPackages', () => {
  const greatest = (versions) => {
    const packages = Object.fromEntries(versions.map((version) => [`x ${version} (${CRATES_IO})`, { name: 'x', version, source: CRATES_IO, checksum: '0'.repeat(64) }]))
    return vendoredPackages({ packages }).find((pkg) => pkg.directory === 'x').version
  }

  it('gives the name alone to the greatest version, a pre-release as the semver crate orders it', () => {
    const ordered = ['1.0.0-alpha', '1.0.0-alpha.1', '1.0.0-alpha.beta', '1.0.0-beta', '1.0.0-beta.2', '1.0.0-beta.11', '1.0.0-rc.1', '1.0.0']
    for (let i = 1; i <= ordered.length; i++) {
      assert.equal(greatest(ordered.slice(0, i).toReversed()), ordered[i - 1])
      assert.equal(greatest(ordered.slice(0, i)), ordered[i - 1])
    }
    assert.equal(greatest(['0.2.0', '0.10.0-rc.1', '0.9.9']), '0.10.0-rc.1')
    assert.equal(greatest(['18446744073709551615.0.0', '18446744073709551614.9.9']), '18446744073709551615.0.0')
    assert.equal(greatest(['1.0.0-2', '1.0.0-10', '1.0.0-a']), '1.0.0-a')
    assert.equal(greatest(['1.0.0-10', '1.0.0-9']), '1.0.0-10')
    assert.throws(() => greatest(['1.0.0+a', '1.0.0+b']), (error) => error instanceof DeptreeError && /differ only in build metadata/u.test(error.message))
  })
})
