    const project = createVfs({ 'Cargo.toml': rootOf([leaf]), 'Cargo.lock': lockOf([appOf([leaf]), leaf]), src: { type: 'directory' } })
    stubCrates([leaf])
    const { vfs } = await buildCargoTree({ project, host: HOST, vfs: project })
    assert.equal(vfs, project)
    assert.deepEqual(project.readdir('/').sort(), ['Cargo.lock', 'Cargo.toml', 'src', 'vendor'])
    assert.equal(project.readText('/vendor/leaf/Cargo.toml'), published('leaf', '1.0.0'))
    await assert.rejects(buildCargoTree({ project, host: HOST, vfs: project }), /^DeptreeError: vfs\["\/vendor"\]: a vendor directory is there already, which is neither kept beside the tree nor removed$/u)
