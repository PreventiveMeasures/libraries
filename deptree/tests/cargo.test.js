    await refused({ 'Cargo.toml': root.replace('[package]\n', '[package]\nworkspace = ".."\n') }, /^DeptreeError: Cargo\.toml: package\.workspace: a root that points to a workspace above it/u)
    await refused({ 'Cargo.toml': root.replace('exclude = [', 'exclude = ["", ') }, /^DeptreeError: Cargo\.toml: workspace\.exclude: the root is excluded from its own workspace, which cargo refuses$/u)
    await refused({ 'Cargo.toml': root.replace('[workspace.package]', 'default-members = ["crates/extra", "patched"]\n\n[workspace.package]') }, /^DeptreeError: Cargo\.toml: workspace\.default-members: "patched" is no member, which cargo refuses$/u)
    await refused({ 'Cargo.toml': root.replace('crates/lib', '../lib') }, /^DeptreeError: Cargo\.toml: dependencies\.lib: "\.\.\/lib" leads out of the project, which is not read$/u)
