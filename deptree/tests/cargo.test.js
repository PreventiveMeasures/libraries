    await refused({ 'crates/.cache/notes': '' }, /^DeptreeError: Cargo\.toml: workspace\.members: "crates\/\.cache\/Cargo\.toml" is not there, which cargo fails on$/u)
    for (const glob of ['crates/**', 'crates/[a-z]*']) await refused({ 'Cargo.toml': root.replace('crates/*', glob) }, /^DeptreeError: Cargo\.toml: workspace\.members\[0\]: ".*" has a `\*\*` or a `\[`, which is not supported$/u)
    await refused({ 'Cargo.toml': root.replace('crates/*', '../crates/*') }, /leads out of the root, which is not read$/u)
    await refused({ 'Cargo.toml': root.replace('crates/*', '/crates/*') }, /is not a relative path within the project, which is all that is read$/u)
    await refused({ 'crates/lib/inner/Cargo.toml': `${files['crates/lib/inner/Cargo.toml']}\n[workspace]\n` }, /^DeptreeError: crates\/lib\/inner\/Cargo\.toml: a member with a \[workspace\] of its own, which cargo refuses$/u)
    await refused({ 'crates/Cargo.toml': '[workspace]\n' }, /^DeptreeError: crates\/Cargo\.toml: a \[workspace\] between a package and the root, one workspace in another, is not supported$/u)
