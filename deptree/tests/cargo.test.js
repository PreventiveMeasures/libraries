const encoder = new TextEncoder()

// As cargo package normalizes a manifest, with `extra` after it.
const published = (name, version, extra = '') => `[package]\nedition = "2021"\nname = "${name}"\nversion = "${version}"\nbuild = false\nautobins = false\nautoexamples = false\nautotests = false\nautobenches = false\n\n[lib]\nname = "${name.replaceAll('-', '_')}"\npath = "src/lib.rs"\n${extra}`

// A .crate as cargo package packs one, a GNU tar gzipped: every entry under
// `<name>-<version>/`. `files` maps a path there to text, or to an entry's
// fields; `entries` are entries as given, by their full names.
async function crate(name, version, files = {}, { extra, entries = [] } = {}) {
  const top = `${name}-${version}`
  const list = [
    { name: `${top}/Cargo.toml`, data: encoder.encode(published(name, version, extra)) },
    { name: `${top}/src/lib.rs`, data: new Uint8Array() },
    ...Object.entries(files).map(([path, file]) => {
      const { data = '', ...fields } = typeof file === 'string' ? { data: file } : file
      return { name: `${top}/${path}`, ...fields, ...(fields.type === undefined || fields.type === 'file' ? { data: encoder.encode(data) } : {}) }
    }),
    ...entries,
  ]
  return gzipped(name, version, await compress(pack(list, { format: 'gnu' }), 'gzip'))
}

const gzipped = (name, version, bytes) => ({ name, version, bytes, checksum: sha256(bytes), key: `${name} ${version} (${CRATES_IO})` })

const crateUrl = (name, version) => `https://static.crates.io/crates/${name}/${name}-${version}.crate`

const stubCrates = (crates) => stubRegistry(crates, crateUrl)

// As cargo writes Cargo.lock: a path package where there is no checksum, each
// dependency by name alone where the lockfile has one package of that name.
function lockOf(packages, tail = '') {
  const entry = ({ name, version, checksum, deps = [] }) => [
    '[[package]]', `name = "${name}"`, `version = "${version}"`,
    ...(checksum === undefined ? [] : [`source = "${CRATES_IO}"`, `checksum = "${checksum}"`]),
    ...(deps.length === 0 ? [] : ['dependencies = [', ...deps.toSorted().map((dep) => ` "${dep}",`), ']']),
  ].join('\n')
  return `# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n${packages.map(entry).join('\n\n')}\n${tail}`
}

const rootOf = (crates) => `[package]\nname = "app"\nversion = "0.1.0"\nedition = "2021"\n\n[dependencies]\n${crates.map((c, i) => `d${i} = { package = "${c.name}", version = "=${c.version}" }\n`).join('')}`
const appOf = (crates) => ({ name: 'app', version: '0.1.0', deps: crates.map(({ name, version }) => (crates.filter((c) => c.name === name).length > 1 ? `${name} ${version}` : name)) })
// A root package depending on each crate, given as text.
const givenOf = (crates) => ({ lockfile: lockOf([appOf(crates), ...crates]), manifests: { '.': rootOf(crates) }, host: HOST })

async function build(crates, options = {}) {
  stubCrates(crates)
  return await buildCargoTree({ ...givenOf(crates), ...options })
}

// The same, read from a project of `files`.
async function read(crates, files) {
  stubCrates(crates)
  return await buildCargoTree({ project: createVfs(files), host: HOST })
}

function listing(vfs, at) {
  const out = {}
  for (const { path, type } of vfs.walk(at)) {
    const { mode } = vfs.lstat(path)
    out[path.slice(at.length + 1) || '.'] = type === 'directory' ? `dir ${mode.toString(8)}` : `${mode.toString(8)} ${path.endsWith('.cargo-checksum.json') ? '' : vfs.readText(path)}`.trimEnd()
  }
  return out
}

