    await assert.rejects(build([leaf], { manifests: { '.': rootOf([leaf]), unread: '[package]\nname = "unread"\nversion = "1.0.0"\n' } }), /^DeptreeError: manifests\["unread"\]: given, but no manifest cargo reads$/u)
    await assert.rejects(build([leaf], { lockfile: 'version = 9\n' }), LockfileError)
    await assert.rejects(build([leaf], { lockfile: 'x = ' }), TomlError)
