    for (const cargo of ['1.93.0', '1.100.0', '1.97', '1.97.0-nightly']) await assert.rejects(build([leaf], { host: { ...HOST, cargo } }), /^DeptreeError: host\.cargo: cargo ".*" is not supported: only cargo 1\.94\.0 to 1\.99\.x are$/u)
